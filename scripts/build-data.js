// Builds the compact data files the dashboard loads from the public datasets in raw/.
// Raw files stay out of Git (see .gitignore); only the small summaries in data/ are published.
//
//   node scripts/build-data.js
//
// EuRepoC (CC BY-NC 4.0): raw/eurepoc/eurepoc_global_dataset_1_3.csv  ->  data/eurepoc.js
// UNSW-NB15 (academic use): raw/unsw-nb15/*.csv                         ->  data/unsw-nb15.js
const fs = require('fs');
const path = require('path');
const {readCsv} = require('./lib/csv');

const ROOT = path.join(__dirname, '..');
const RAW = path.join(ROOT, 'raw');
const OUT = path.join(ROOT, 'data');

const split = (v) => [...new Set(String(v || '').split(';').map((s) => s.trim()).filter(Boolean))];
const known = (v) => v && !/^(not available|unknown|not attributed|none)$/i.test(v);

function countBy(rows, pick, keep = () => true) {
  const m = new Map();
  rows.forEach((r) => split(pick(r)).filter(keep).forEach((v) => m.set(v, (m.get(v) || 0) + 1)));
  return [...m.entries()].sort((a, b) => b[1] - a[1]);
}

function writeData(file, name, data) {
  fs.mkdirSync(OUT, {recursive: true});
  const body = '// Generated by scripts/build-data.js. Do not edit by hand.\nwindow.' + name + ' = ' + JSON.stringify(data) + ';\n';
  fs.writeFileSync(path.join(OUT, file), body);
  console.log('wrote data/' + file + ' (' + (body.length / 1024).toFixed(1) + ' KB)');
}

// ---- EuRepoC ----
const TYPE_ID = {
  'Hijacking with Misuse': 'Pembajakan sistem (disalahgunakan)',
  'Hijacking without Misuse': 'Pembajakan sistem (tanpa penyalahgunaan)',
  'Disruption': 'Gangguan layanan',
  'Data theft': 'Pencurian data',
  'Data theft & Doxing': 'Pencurian data & doxing',
  'Ransomware': 'Ransomware',
};
const SECTOR_ID = {
  'Critical infrastructure': 'Infrastruktur kritis',
  'State institutions / political system': 'Institusi negara / politik',
  'Media': 'Media',
  'Social groups': 'Kelompok sosial',
  'Education': 'Pendidikan',
  'Science': 'Riset / sains',
  'End user(s) / specially protected groups': 'Pengguna akhir',
  'International / supranational organization': 'Organisasi internasional',
};
const ACTOR_ID = {
  'Non-state-group': 'Kelompok non-negara',
  'Not attributed': 'Belum diatribusi',
  'State affiliated actor': 'Aktor terafiliasi negara',
  'State': 'Negara',
  'Unknown': 'Tidak diketahui',
  'Individual hacker(s)': 'Peretas individu',
};
const sector = (v) => (v.startsWith('Corporate Targets') ? 'Korporasi' : SECTOR_ID[v] || v);

function buildEurepoc() {
  const file = path.join(RAW, 'eurepoc', 'eurepoc_global_dataset_1_3.csv');
  if (!fs.existsSync(file)) { console.log('skip EuRepoC: ' + file + ' not found'); return; }
  const rows = readCsv(file).map((r) => {
    const m = /^(\d{2})\.(\d{2})\.(\d{4})$/.exec(r.start_date.trim());
    return {...r, iso: m ? m[3] + '-' + m[2] + '-' + m[1] : '', year: m ? +m[3] : null};
  });
  const dated = rows.filter((r) => r.year);
  const years = [...new Set(dated.map((r) => r.year))].sort((a, b) => a - b);
  const typeKeys = Object.keys(TYPE_ID);

  const byYear = years.map((y) => {
    const ys = dated.filter((r) => r.year === y);
    const o = {year: y, total: ys.length};
    typeKeys.forEach((t) => { o[t] = ys.filter((r) => split(r.incident_type).includes(t)).length; });
    return o;
  });

  const top = (pick, n, keep = known, label = (v) => v) =>
    countBy(rows, pick, keep).slice(0, n).map(([k, v]) => ({name: label(k), incidents: v}));

  const lastYear = years[years.length - 1];
  const recentPick = (r) => ({
    id: r.incident_id,
    name: r.name.trim(),
    date: r.iso,
    types: split(r.incident_type).filter((t) => TYPE_ID[t]).map((t) => TYPE_ID[t]),
    receiver_country: split(r.receiver_country).filter(known).slice(0, 3),
    sectors: [...new Set(split(r.receiver_category).filter(known).map(sector))].slice(0, 3),
    initiator_country: split(r.initiator_country).filter(known)[0] || '',
    initiator_category: ACTOR_ID[split(r.initiator_category)[0]] || 'Tidak diketahui',
    intensity: Number(r.weighted_intensity) || 0,
  });
  const byDate = [...dated].sort((a, b) => b.iso.localeCompare(a.iso));
  const recent = byDate.slice(0, 40).map(recentPick);
  const indonesia = byDate.filter((r) => split(r.receiver_country).includes('Indonesia')).map(recentPick);

  const attributedState = rows.filter((r) => split(r.initiator_category).some((c) => c === 'State' || c === 'State affiliated actor')).length;

  writeData('eurepoc.js', 'EUREPOC', {
    source: {
      name: 'EuRepoC Global Dataset of Cyber Incidents v1.3',
      url: 'https://doi.org/10.5281/zenodo.14965395',
      license: 'CC BY-NC 4.0',
      citation: 'European Repository of Cyber Incidents (EuRepoC), Global Dataset of Cyber Incidents, versi 1.3, Zenodo, 2025.',
    },
    totals: {
      incidents: rows.length,
      first_year: years[0],
      last_year: lastYear,
      last_year_incidents: dated.filter((r) => r.year === lastYear).length,
      state_linked: attributedState,
      ransomware: rows.filter((r) => split(r.incident_type).includes('Ransomware')).length,
      zero_days: rows.filter((r) => r.zero_days.trim() === 'Yes').length,
      disruption: rows.filter((r) => r.has_disruption.trim() === 'True').length,
      indonesia: indonesia.length,
    },
    types: typeKeys.map((t) => ({key: t, name: TYPE_ID[t]})),
    by_year: byYear,
    receiver_countries: top((r) => r.receiver_country, 10),
    initiator_countries: top((r) => r.initiator_country, 10),
    initiator_categories: top((r) => r.initiator_category, 6, (v) => v && v !== 'Other', (v) => ACTOR_ID[v] || v),
    sectors: countBy(rows, (r) => split(r.receiver_category).map(sector).join(';'), known).slice(0, 8).map(([k, v]) => ({name: k, incidents: v})),
    mitre_initial_access: top((r) => r.mitre_initial_access, 6),
    mitre_impact: top((r) => r.mitre_impact, 6),
    recent,
    indonesia,
  });
}

// ---- UNSW-NB15 ----
// The full-record files (UNSW-NB15_1..4.csv) have no header row; column names come from the
// features file (spelled "NUSW-NB15_features.csv" in the official download).
// Severity per attack category is our own SOC triage choice, not part of the dataset.
const UNSW_SEVERITY = {
  Backdoor: 'Critical', Shellcode: 'Critical', Worms: 'Critical',
  Exploits: 'High', DoS: 'High',
  Reconnaissance: 'Medium', Fuzzers: 'Medium', Analysis: 'Medium',
  Generic: 'Low',
};
const UNSW_ID = {
  Backdoor: 'Backdoor', Shellcode: 'Shellcode', Worms: 'Worm', Exploits: 'Eksploitasi kerentanan', DoS: 'Denial of Service',
  Reconnaissance: 'Pengintaian / pemindaian', Fuzzers: 'Fuzzing', Analysis: 'Analisis (port scan, spam, HTML)', Generic: 'Serangan generik (cipher)',
};
const UNSW_BIN = 600;
const unswCat = (v) => {
  const c = v.trim();
  return c === 'Backdoors' ? 'Backdoor' : c;
};

async function buildUnsw() {
  const dir = path.join(RAW, 'unsw-nb15');
  const files = fs.existsSync(dir) ? fs.readdirSync(dir) : [];
  const featFile = files.find((f) => /features\.csv$/i.test(f));
  const dataFiles = files.filter((f) => /^UNSW-NB15_\d\.csv$/i.test(f)).sort();
  if (!featFile || !dataFiles.length) { console.log('skip UNSW-NB15: need *features.csv and UNSW-NB15_<n>.csv in ' + dir); return; }

  const cols = readCsv(path.join(dir, featFile)).map((r) => r.Name.trim().toLowerCase().replace(/\s+/g, ''));
  const ix = (name) => {
    const i = cols.indexOf(name);
    if (i < 0) throw new Error('UNSW-NB15 column missing: ' + name);
    return i;
  };
  const C = {src: ix('srcip'), dst: ix('dstip'), dport: ix('dsport'), proto: ix('proto'), service: ix('service'), stime: ix('stime'), cat: ix('attack_cat'), label: ix('label')};

  const readline = require('readline');
  let flows = 0;
  let attacks = 0;
  let tMin = Infinity;
  let tMax = -Infinity;
  const cats = new Map();
  const timeline = new Map();
  const srcs = new Map();
  const dsts = new Map();
  const services = new Map();
  const groups = new Map();
  const inc = (m, k, n = 1) => m.set(k, (m.get(k) || 0) + n);

  for (const f of dataFiles) {
    const rl = readline.createInterface({input: fs.createReadStream(path.join(dir, f), 'utf8'), crlfDelay: Infinity});
    for await (let line of rl) {
      line = line.replace(/^﻿/, '');
      if (!line) continue;
      const v = line.split(',');
      flows++;
      const t = Number(v[C.stime]);
      if (t) { tMin = Math.min(tMin, t); tMax = Math.max(tMax, t); }
      if (v[C.label].trim() !== '1') continue;
      attacks++;
      const cat = unswCat(v[C.cat]) || 'Tidak berlabel';
      inc(cats, cat);
      // Attacks in UNSW-NB15_1 span about two hours, so bucket by 10 minutes
      const bin = Math.floor(t / UNSW_BIN) * UNSW_BIN;
      if (!timeline.has(bin)) timeline.set(bin, {});
      const h = timeline.get(bin);
      h[cat] = (h[cat] || 0) + 1;
      inc(srcs, v[C.src]);
      inc(dsts, v[C.dst]);
      const svc = v[C.service] && v[C.service] !== '-' ? v[C.service] : v[C.proto] + '/' + v[C.dport];
      inc(services, svc);
      // Group like a SIEM would: same category, source, destination and service in one alert
      const key = [cat, v[C.src], v[C.dst], svc].join('|');
      const g = groups.get(key);
      if (g) { g.count++; g.first = Math.min(g.first, t); g.last = Math.max(g.last, t); }
      else groups.set(key, {category: cat, src: v[C.src], dst: v[C.dst], service: svc, count: 1, first: t, last: t});
    }
  }

  const topN = (m, n, k = 'name') => [...m.entries()].sort((a, b) => b[1] - a[1]).slice(0, n).map(([name, count]) => ({[k]: name, flows: count}));
  const sev = (c) => UNSW_SEVERITY[c] || 'Medium';
  const rank = {Critical: 0, High: 1, Medium: 2, Low: 3};
  const allGroups = [...groups.values()];
  // Keep every critical group plus the largest of the rest, so the list stays small
  const picked = [
    ...allGroups.filter((g) => sev(g.category) === 'Critical').sort((a, b) => b.count - a.count).slice(0, 25),
    ...allGroups.filter((g) => sev(g.category) !== 'Critical').sort((a, b) => b.count - a.count).slice(0, 35),
  ].sort((a, b) => rank[sev(a.category)] - rank[sev(b.category)] || b.count - a.count)
    .map((g, i) => ({id: 'IDS-' + String(i + 1).padStart(4, '0'), ...g, severity: sev(g.category), name: UNSW_ID[g.category] || g.category}));

  writeData('unsw-nb15.js', 'UNSW', {
    source: {
      name: 'UNSW-NB15 (' + dataFiles.join(', ') + ')',
      url: 'https://research.unsw.edu.au/projects/unsw-nb15-dataset',
      license: 'Gratis untuk riset akademik; penggunaan komersial perlu izin penulis',
      citation: 'Moustafa, N. & Slay, J. (2015). UNSW-NB15: a comprehensive data set for network intrusion detection systems. MilCIS 2015.',
    },
    severity_map: UNSW_SEVERITY,
    totals: {flows, attacks, normal: flows - attacks, start: tMin, end: tMax, attack_sources: srcs.size, attack_targets: dsts.size, alert_groups: groups.size},
    categories: [...cats.entries()].sort((a, b) => b[1] - a[1]).map(([name, n]) => ({key: name, name: UNSW_ID[name] || name, severity: sev(name), flows: n})),
    bin_seconds: UNSW_BIN,
    timeline: [...timeline.entries()].sort((a, b) => a[0] - b[0]).map(([t, c]) => ({t, ...c})),
    top_sources: topN(srcs, 8, 'ip'),
    top_targets: topN(dsts, 8, 'ip'),
    top_services: topN(services, 8, 'service'),
    alerts: picked,
  });
}

(async () => {
  buildEurepoc();
  await buildUnsw();
})();
